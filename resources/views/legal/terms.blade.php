<section id="scope">
    <h2>1. Saklaw ng KaBarangay</h2>
    <p>Ang KaBarangay ay portal para sa resident registration, barangay certificate requests, Lupon complaints at kaugnay na records, sector services, announcements, at iba pang serbisyong available sa napili mong barangay. Maaaring magkaiba ang requirements at available na serbisyo ayon sa barangay at uri ng request.</p>
    <p>Gamitin ang portal ayon sa mga tuntuning ito at sa naaangkop na batas. Ang mga patakarang ito ay hindi kapalit ng opisyal na proseso o umiiral na karapatan sa pagkuha ng barangay services. Kung hindi mo magamit ang online portal, makipag-ugnayan sa barangay office para sa alternatibong paraan ng pagproseso.</p>
</section>
<section id="accounts">
    <h2>2. Registration at responsibilidad sa account</h2>
    <ul>
        <li>Gamitin ang iyong tunay na impormasyon at piliin ang barangay at purok kung saan ka aktuwal na naninirahan. Ipaayos sa administrator ang maling detalye.</li>
        <li>Magsumite lamang ng dokumentong tunay at may karapatan kang gamitin. Kung kumikilos para sa ibang tao, kailangan ang kaukulang pahintulot o awtoridad.</li>
        <li>Ang registration ay sasailalim sa pagsusuri. Ang pagsumite ng application o pagkakaroon ng email address ay hindi pa kumpirmasyon ng residency o approval.</li>
        <li>Panatilihing pribado ang password at password-reset links. Mag-log out sa shared device at i-report sa administrator ang pinaghihinalaang unauthorized access.</li>
    </ul>
</section>
<section id="requests">
    <h2>3. Requests, bayad, at opisyal na approval</h2>
    <p>Ang matagumpay na submission at reference number ay patunay na naitala ang request, hindi garantiya ng approval, pagiging eligible, o takdang petsa ng release. Maaaring kailanganin ang karagdagang dokumento, correction, personal appearance, verification, o opisyal na bayad o waiver.</p>
    <p>Sundin ang kasalukuyang Citizen’s Charter, instructions sa request, at kumpirmasyon ng awtorisadong barangay personnel. Huwag magbayad sa personal na account o hindi beripikadong payment channel. Ang dokumentong may label na draft, prepared copy, o for review ay hindi pa awtomatikong pirmado o opisyal na released.</p>
    <p>Para sa Lupon, hindi pinapalitan ng online complaint, hearing status, o AI response ang mga kinakailangang notice, aktuwal na pagdinig, pirma, kasunduan, at iba pang opisyal na hakbang.</p>
</section>
<section id="conduct">
    <h2>4. Mga patakaran sa wastong paggamit</h2>
    <ul>
        <li>Huwag magpanggap bilang ibang tao, mag-upload ng pekeng dokumento, o sadyang magbigay ng mapanlinlang na impormasyon.</li>
        <li>Huwag subukang buksan, baguhin, o ibahagi ang records ng ibang residente nang walang awtoridad.</li>
        <li>Huwag mag-upload ng malware, manghimasok sa account o seguridad, o gumamit ng automated requests upang guluhin ang serbisyo.</li>
        <li>Huwag maglagay ng hindi kailangang sensitibong impormasyon tungkol sa ibang tao. Ang lehitimong reklamo at kaugnay na ebidensiya ay dapat isumite sa tamang form at opisyal na proseso.</li>
    </ul>
</section>
<section id="notifications">
    <h2>5. Emails at service notifications</h2>
    <p>Maaaring magpadala ang system ng password-reset links, registration decisions, requests for correction, at iba pang kaugnay na service notifications sa email na ibinigay mo. Siguraduhing tama at ikaw ang may access sa email address na iyon.</p>
    <p>Maaaring maantala o mapunta sa spam folder ang email. Ang mensahe sa form na natanggap ang request ay hindi garantiya na naihatid na ang email. Tingnan din ang iyong account o application page at makipag-ugnayan sa administrator kung may hindi malinaw. Hindi dapat ibigay sa kawani o sa chat ang iyong password o reset token.</p>
</section>
<section id="ai">
    <h2>6. Paggamit ng Kabarangay AI</h2>
    <p>Opsiyonal na gabay ang AI assistant para sa system at available na serbisyo. Maaari itong magkamali, maging kulang, o hindi sumabay sa pinakabagong pagbabago. Kumpirmahin sa aktuwal na request page, Citizen’s Charter, o awtorisadong kawani ang mahalagang requirement, bayad, iskedyul, o desisyon.</p>
    <p>Ang chat ay hindi naghahain ng application o reklamo, hindi nag-aapruba ng request, at hindi nagbibigay ng opisyal na legal na desisyon. Huwag gamitin bilang emergency channel. Para sa agarang panganib, direktang makipag-ugnayan sa nararapat na emergency service.</p>
    <p>Basahin ang <a href="/privacy-policy#ai">AI section ng Privacy Policy</a> bago magbahagi ng impormasyon sa chat.</p>
</section>
<section id="availability">
    <h2>7. Availability at account access</h2>
    <p>Maaaring maantala o pansamantalang hindi ma-access ang portal dahil sa maintenance, internet problems, hosting limits, o technical failure. Kung may deadline o agarang pangangailangan, direktang kontakin ang barangay office at huwag umasa lamang sa online submission o email.</p>
    <p>Maaaring limitahan o i-deactivate ng awtorisadong administrator ang account kapag may kailangang verification, pinaghihinalaang compromise, o paglabag sa wastong paggamit, ayon sa naaangkop na proseso. Makipag-ugnayan sa administrator upang humingi ng paliwanag, correction, o pagsusuri. Ang limitasyon sa online account ay hindi awtomatikong nag-aalis ng karapatan sa mga serbisyong itinakda ng batas.</p>
</section>
